#!/usr/bin/env node
// Generates db/migrations/0705_patient_staff_policy_qualify.sql (SEC03-F01).
//
// 0702 wrote the T-STAFF predicate as `s.patient_id = patient_id`; the unqualified name binds to the sub-query alias, so
// the stored predicate was `s.patient_id = s.patient_id` (always true) in 21 policies. This script is the one template
// (ARCHITECTURE 21.4): it reads every policy statement of 0702 that contains the tautology and emits an ALTER POLICY with
// the column qualified by the table name. Nothing else in a policy changes (roles, other clauses, command).
//
//   node db/tools/gen-staff-policies.mjs          write the migration
//   node db/tools/gen-staff-policies.mjs --check  fail if the committed migration differs from the generated text
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const source = `${root}db/migrations/0702_patient_rls_and_grants.sql`;
const target = `${root}db/migrations/0705_patient_staff_policy_qualify.sql`;
export const EXPECTED_POLICIES = 21;
const BAD = 's.patient_id = patient_id';

export function generate() {
  const statements = readFileSync(source, 'utf8').split(/;\n/);
  const out = [];
  for (const raw of statements) {
    const m = /CREATE POLICY (\w+) ON ([\w.]+)\n\s+FOR \w+ TO \w+\n([\s\S]*)$/.exec(
      raw.replace(/^(--.*\n|\n)+/gm, ''),
    );
    if (!m || !m[3].includes(BAD)) continue;
    const [, name, table, body] = m;
    const column = `${table.split('.')[1]}.patient_id`;
    out.push(
      `ALTER POLICY ${name} ON ${table}\n${body.replaceAll(BAD, `s.patient_id = ${column}`)};`,
    );
  }
  if (out.length !== EXPECTED_POLICIES)
    throw new Error(`expected ${EXPECTED_POLICIES} policies, found ${out.length}`);
  return `-- migration-class: expand
-- SEC03-F01: qualify the column in the 21 T-STAFF policies of 0702 (and the identity/notifications ones it adds).
-- The unqualified \`patient_id\` bound to the sub-query alias, so \`s.patient_id = patient_id\` was \`s.patient_id = s.patient_id\`:
-- any staff member with one patient at a location read and wrote the child rows of every patient in the organisation.
-- GENERATED by db/tools/gen-staff-policies.mjs from 0702 (one template, ARCHITECTURE 21.4); do not edit by hand, CI checks parity.
-- Policies are altered, not recreated: roles and every other clause stay as 0702 wrote them.

${out.join('\n\n')}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate();
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== text) {
      console.error(
        '0705 differs from the generated text; run node db/tools/gen-staff-policies.mjs',
      );
      process.exit(1);
    }
  } else writeFileSync(target, text);
}
